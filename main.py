from flask import Flask, render_template, request
from data import items  # <-- берём данные отсюда

app = Flask(__name__)

# Построим структуру категорий и подкатегорий
data = {}
for item in items:
    cat = item["category"]
    sub = item["subcategory"]
    data.setdefault(cat, {}).setdefault(sub, []).append(item)

@app.route('/')
def index():
    search_query = request.args.get('search', '').lower()
    selected_category = request.args.get('category', '')
    selected_subcategory = request.args.get('subcategory', '')
    sort_by = request.args.get('sort', '')

    filtered_items = items.copy()

    # Поиск
    if search_query:
        filtered_items = [
            item for item in filtered_items
            if search_query in item['name'].lower()
            or search_query in item['short'].lower()
            or search_query in item['description'].lower()
        ]

    # Фильтрация по категории
    if selected_category:
        filtered_items = [
            item for item in filtered_items
            if item['category'] == selected_category
        ]

    # Фильтрация по подкатегории
    if selected_subcategory:
        filtered_items = [
            item for item in filtered_items
            if item['subcategory'] == selected_subcategory
        ]

    # Сортировка
    if sort_by == 'name':
        filtered_items.sort(key=lambda x: x['name'].lower())
    elif sort_by == 'category':
        filtered_items.sort(key=lambda x: (x['category'].lower(), x['subcategory'].lower()))

    return render_template(
        'index.html',
        items=filtered_items,
        data=data,
        selected_category=selected_category,
        selected_subcategory=selected_subcategory
    )

if __name__ == '__main__':
    app.run(debug=True)

